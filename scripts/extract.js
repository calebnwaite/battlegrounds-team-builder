import {readFileSync} from 'node:fs';
import {buildCatalog, readJson, sha256, writeCatalog} from './lib/catalog.js';
const source = process.argv[2];
if (!source) throw new Error('Pass the downloaded pinned-build cards.json path. See README.');
const info = readJson(new URL('../public/build.json', import.meta.url));
const raw = readFileSync(source);
if (sha256(raw) !== info.sha256) throw new Error(`Source SHA256 does not match pinned build ${info.build}; catalog not written.`);
const catalog = buildCatalog(JSON.parse(raw.toString()));
writeCatalog(new URL('../public/catalog.json', import.meta.url), catalog);
console.log(`Extracted ${catalog.minions.length} minions and ${catalog.trinkets.length} trinkets.`);
